const fs = require('node:fs')
const path = require('node:path')
const GUIDES = require('../data/style-guides.js')
const { NOTE_URL } = require('../lib/inspiration.js')

function validateNotes(input) {
  if (!Array.isArray(input)) throw new Error('笔记清单必须是 JSON 数组')
  const seen = new Set()
  return input.map((item, index) => {
    if (!item || typeof item !== 'object' || Array.isArray(item)) throw new Error(`第 ${index + 1} 条不是对象`)
    const { id, styleId, kind, title, author, url } = item
    if (typeof id !== 'string' || !/^[a-z0-9_-]{3,50}$/i.test(id) || seen.has(id)) throw new Error(`第 ${index + 1} 条 id 无效或重复`)
    if (!GUIDES[styleId]) throw new Error(`第 ${index + 1} 条风格不存在`)
    if (!['look', 'makeup'].includes(kind)) throw new Error(`第 ${index + 1} 条类别无效`)
    if (typeof title !== 'string' || !title.trim() || title.length > 60) throw new Error(`第 ${index + 1} 条标题无效`)
    if (typeof author !== 'string' || !author.trim() || author.length > 40) throw new Error(`第 ${index + 1} 条作者无效`)
    if (typeof url !== 'string' || !NOTE_URL.test(url)) throw new Error(`第 ${index + 1} 条不是小红书原文链接`)
    if (Object.keys(item).some(key => !['id', 'styleId', 'kind', 'title', 'author', 'url'].includes(key))) {
      throw new Error(`第 ${index + 1} 条含未经授权的正文或图片字段`)
    }
    seen.add(id)
    return { id, styleId, kind, title: title.trim(), author: author.trim(), url }
  })
}

if (require.main === module) {
  if (!process.argv[2]) throw new Error('用法：node scripts/import-inspiration-notes.js /absolute/path/notes.json')
  const source = path.resolve(process.argv[2])
  const entries = validateNotes(JSON.parse(fs.readFileSync(source, 'utf8')))
  const destination = path.join(__dirname, '../data/inspiration-notes.json')
  fs.writeFileSync(destination, `${JSON.stringify(entries, null, 2)}\n`)
  fs.writeFileSync(path.join(__dirname, '../data/inspiration-notes.js'),
    `// Generated by scripts/import-inspiration-notes.js after editorial verification.\nmodule.exports = ${JSON.stringify(entries, null, 2)}\n`)
  process.stdout.write(`已导入 ${entries.length} 条笔记元数据；请手动打开每条原文核对作者、标题和内容。\n`)
}

module.exports = { validateNotes }
