const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..')
const candidates = require(path.join(root, 'data/creator-candidates.json'))
const curated = require(path.join(root, 'data/curated-creator-sources.json'))
const PROFILE_URL = /^https:\/\/www\.xiaohongshu\.com\/user\/profile\/([0-9a-f]{24})$/i

function normalizeCreator(creator, fallbackStyles) {
  const match = typeof creator.profileUrl === 'string' && creator.profileUrl.match(PROFILE_URL)
  if (!match) throw new Error(`缺少规范主页链接：${creator.handle}`)
  return {
    id: match[1],
    name: creator.observedDisplayName || creator.handle,
    redId: creator.redId,
    profileUrl: creator.profileUrl,
    accountType: creator.accountType || 'creator',
    styleIds: creator.styleIds || fallbackStyles || [],
    styleTags: creator.styleTags || [],
    cue: creator.cue
  }
}

const verified = []
for (const group of candidates.groups) {
  for (const creator of group.creators) {
    if (creator.identityStatus !== 'profile_verified') continue
    verified.push(normalizeCreator(creator, group.styleIds))
  }
}
for (const source of curated.sources) {
  for (const creator of source.creators) {
    if (creator.identityStatus !== 'profile_verified') continue
    verified.push(normalizeCreator(creator, []))
  }
}

const ids = new Set(verified.map(creator => creator.id))
if (verified.length !== 16 || ids.size !== verified.length) {
  throw new Error(`已核对账号应为 16 个且不能重复，当前 ${verified.length} 个、去重后 ${ids.size} 个`)
}
for (const creator of verified) {
  if (!creator.name || !creator.redId || !creator.cue || !creator.styleIds.length) {
    throw new Error(`账号资料不完整：${creator.name || creator.id}`)
  }
}

const output = `// Generated by scripts/build-verified-creators.js.\n// Metadata only: no copied note text, images or videos.\nmodule.exports = ${JSON.stringify(verified, null, 2)}\n`
fs.writeFileSync(path.join(root, 'data/verified-creators.js'), output)
console.log(`generated ${verified.length} verified creator profiles`)

module.exports = { normalizeCreator }
